CREATE FUNCTION set_reservation_listing() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  SELECT listing_id INTO NEW.listing_id
  FROM order_lines WHERE order_id = NEW.order_id AND line_no = NEW.line_no;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Order line (%, %) does not exist', NEW.order_id, NEW.line_no
      USING ERRCODE = '23503';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER reservation_listing BEFORE INSERT OR UPDATE OF order_id, line_no ON stock_reservations
  FOR EACH ROW EXECUTE FUNCTION set_reservation_listing();

CREATE FUNCTION check_order_allocation(checked_order integer) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  UPDATE orders SET placed_at = placed_at WHERE order_id = checked_order;
  IF NOT FOUND THEN RETURN; END IF;

  IF EXISTS (
    SELECT 1 FROM order_lines l
    LEFT JOIN stock_reservations r USING (order_id, line_no)
    WHERE l.order_id = checked_order
    GROUP BY l.line_no, l.quantity
    HAVING COALESCE(SUM(r.quantity), 0) <> l.quantity
  ) THEN
    RAISE EXCEPTION 'Reservations must total the ordered quantity in order %', checked_order
      USING ERRCODE = '23514';
  END IF;

  IF EXISTS (
    SELECT 1 FROM fulfillment_lines fl
    JOIN fulfillments f USING (fulfillment_id, order_id)
    LEFT JOIN stock_reservations r USING (order_id, line_no, seller_id, warehouse_id)
    WHERE fl.order_id = checked_order
    GROUP BY fl.line_no, f.seller_id, f.warehouse_id, r.quantity
    HAVING SUM(fl.quantity) > COALESCE(r.quantity, 0)
  ) THEN
    RAISE EXCEPTION 'Fulfillment exceeds the stock reserved for its seller and warehouse in order %', checked_order
      USING ERRCODE = '23514';
  END IF;

  IF EXISTS (
    SELECT 1 FROM return_lines rl
    JOIN return_requests rr USING (return_id, order_id)
    JOIN order_lines l USING (order_id, line_no)
    WHERE rl.order_id = checked_order AND rr.status <> 'rejected'
    GROUP BY rl.line_no, l.quantity
    HAVING SUM(rl.quantity) > l.quantity
  ) THEN
    RAISE EXCEPTION 'Active returns exceed the ordered quantity in order %', checked_order
      USING ERRCODE = '23514';
  END IF;
END $$;

CREATE FUNCTION check_changed_orders() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP <> 'INSERT' THEN
    PERFORM check_order_allocation(OLD.order_id);
  END IF;
  IF TG_OP = 'INSERT' OR (TG_OP = 'UPDATE' AND NEW.order_id <> OLD.order_id) THEN
    PERFORM check_order_allocation(NEW.order_id);
  END IF;
  RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER order_line_allocation AFTER INSERT OR UPDATE OR DELETE ON order_lines
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_changed_orders();
CREATE CONSTRAINT TRIGGER reserved_allocation AFTER INSERT OR UPDATE OR DELETE ON stock_reservations
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_changed_orders();
CREATE CONSTRAINT TRIGGER fulfilled_allocation AFTER INSERT OR UPDATE OR DELETE ON fulfillment_lines
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_changed_orders();
CREATE CONSTRAINT TRIGGER fulfillment_source AFTER UPDATE OF seller_id, warehouse_id ON fulfillments
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_changed_orders();
CREATE CONSTRAINT TRIGGER returned_allocation AFTER INSERT OR UPDATE OR DELETE ON return_lines
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_changed_orders();
CREATE CONSTRAINT TRIGGER active_returns AFTER UPDATE OF status ON return_requests
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_changed_orders();

CREATE FUNCTION recheck_truncated_reservations() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE order_lines SET quantity = quantity;
  RETURN NULL;
END $$;
CREATE TRIGGER truncated_reservations AFTER TRUNCATE ON stock_reservations
  FOR EACH STATEMENT EXECUTE FUNCTION recheck_truncated_reservations();

